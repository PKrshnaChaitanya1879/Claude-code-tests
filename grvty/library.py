"""Named looks: films and shows, Indian cinema, photographers, film stocks and
camera simulations, Instagram aesthetics and moods.

Each look is real slider settings (the same ones Lightroom has), so a look
found here can be varied, fine-tuned and saved as a preset like any other.
`looks.parse()` matches these names, aliases and keywords, with typo fixing.

Hue reference for colour grading: red 0, orange 30, gold 45, yellow 60,
green 120, teal 180, cyan 195, blue 220, violet 270, magenta 320.
"""
from .params import HUES


def G(sh=None, mid=None, hi=None, gl=None, bal=0):
    """Colour grading wheels; each wheel is (hue, sat) or (hue, sat, lum)."""
    g = {}
    for k, v in (("shadows", sh), ("midtones", mid), ("highlights", hi), ("global", gl)):
        if v:
            g[k] = {"hue": v[0], "sat": v[1], "lum": v[2] if len(v) > 2 else 0}
    if bal:
        g["balance"] = bal
    return g


def fade(lift, roll=245):
    """Lifted (matte) blacks and slightly rolled-off whites."""
    return [[0, lift], [64, 64 + lift // 2], [192, 192 + (roll - 255) // 2], [255, roll]]


def scurve(n):
    """A classic S-curve; n is the strength in levels."""
    return [[0, 0], [64, 64 - n], [192, 192 + n], [255, 255]]


def keep(*hues, boost=20):
    """Colour mixer: drain every colour except these (selective colour)."""
    return {h: (boost if h in hues else -100) for h in HUES}


def L(name, aliases, params, keys=""):
    return {"name": name, "aliases": aliases, "params": params, "keys": keys.split()}


